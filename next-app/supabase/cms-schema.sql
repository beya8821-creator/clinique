create extension if not exists citext;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name varchar(120),
  role text not null default 'editor' check (role in ('admin', 'editor')),
  status text not null default 'active' check (status in ('active', 'disabled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select role from public.profiles where id = auth.uid() and status = 'active';
$$;

create or replace function public.is_editor_or_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_user_role() in ('admin', 'editor');
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.current_user_role() = 'admin';
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.pages (
  id integer generated by default as identity primary key,
  title varchar(190) not null,
  slug varchar(190) not null unique,
  template_file varchar(190),
  html_content text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cms_sections (
  id integer generated by default as identity primary key,
  page_slug varchar(80) not null,
  section_key varchar(80) not null,
  label varchar(120) not null,
  title varchar(255),
  subtitle text,
  body text,
  button_text varchar(120),
  button_url text,
  image_path text,
  video_url text,
  extra_json jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (page_slug, section_key)
);

create table if not exists public.cms_services (
  id integer generated by default as identity primary key,
  title varchar(190) not null,
  slug varchar(190) not null unique,
  description text not null,
  image_path text not null,
  icon_class varchar(120) not null,
  button_text varchar(120) default 'Learn More',
  button_url text default '/service-details',
  features_text text,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.cms_contact_settings (
  id integer generated by default as identity primary key,
  setting_key varchar(120) not null unique,
  setting_value text,
  is_public boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.hero_slider (
  id integer generated by default as identity primary key,
  image text not null,
  title varchar(190),
  subtitle varchar(255),
  button_text varchar(120),
  button_link text,
  display_order integer not null default 0,
  status boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.media_library (
  id integer generated by default as identity primary key,
  filename varchar(190) not null,
  original_name varchar(190) not null,
  path text not null,
  storage_bucket text not null default 'media',
