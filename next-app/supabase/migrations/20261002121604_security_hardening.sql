create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;
alter function public.current_user_role() set schema private;
alter function public.is_editor_or_admin() set schema private;
alter function public.is_admin() set schema private;
create or replace function private.current_user_role() returns text language sql stable security definer set search_path = public as $$ select role from public.profiles where id = auth.uid() and status = 'active'; $$;
create or replace function private.is_editor_or_admin() returns boolean language sql stable security definer set search_path = public, private as $$ select private.current_user_role() in ('admin', 'editor'); $$;
create or replace function private.is_admin() returns boolean language sql stable security definer set search_path = public, private as $$ select private.current_user_role() = 'admin'; $$;
revoke all on function private.current_user_role() from public;
revoke all on function private.is_editor_or_admin() from public;
revoke all on function private.is_admin() from public;
grant execute on function private.current_user_role() to authenticated;
grant execute on function private.is_editor_or_admin() to authenticated;
grant execute on function private.is_admin() to authenticated;
alter function public.set_updated_at() set search_path = public;
drop policy if exists "Public can read active pages" on public.pages;
create policy "Public can read active pages" on public.pages for select to anon using (is_active = true);
drop policy if exists "Public can read cms sections" on public.cms_sections;
create policy "Public can read cms sections" on public.cms_sections for select to anon using (true);
drop policy if exists "Public can read active services" on public.cms_services;
create policy "Public can read active services" on public.cms_services for select to anon using (is_active = true);
drop policy if exists "Public can read public contact settings" on public.cms_contact_settings;
create policy "Public can read public contact settings" on public.cms_contact_settings for select to anon using (is_public = true);
drop policy if exists "Public can read active hero slides" on public.hero_slider;
create policy "Public can read active hero slides" on public.hero_slider for select to anon using (status = true);
drop policy if exists "Users can read their profile" on public.profiles;
create policy "Users can read their profile" on public.profiles for select to authenticated using (id = (select auth.uid()) or private.is_admin());
drop policy if exists "Editors can read newsletter subscribers" on public.newsletter_subscribers;
create policy "Editors can read newsletter subscribers" on public.newsletter_subscribers for select to authenticated using (private.is_editor_or_admin());
drop policy if exists "Editors can update newsletter subscribers" on public.newsletter_subscribers;
create policy "Editors can update newsletter subscribers" on public.newsletter_subscribers for update to authenticated using (private.is_editor_or_admin()) with check (private.is_editor_or_admin());
